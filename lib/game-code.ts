function pickWord(): string {
  const w = WORDS5[Math.floor(Math.random() * WORDS5.length)]!;
  return w.toLowerCase();
}

export function generateGameCodeWords(): { word1: string; word2: string } {
  let word1 = pickWord();
  let word2 = pickWord();
  let guard = 0;
  while (word2 === word1 && guard++ < 30) {
    word2 = pickWord();
  }
  return { word1, word2 };
}
